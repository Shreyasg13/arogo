def test_orphan_cleanup_removes_only_orphans(app):
    c, uid = _uid(app, "stor12@medeasy.test")
    _write(app, "keep-me.pdf"); _add_report(uid, "keep-me.pdf")
    _write(app, "drop-me.pdf")
