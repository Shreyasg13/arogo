"""Uploaded files on a finite SD card.

Two live problems these tests lock down.

Deleting an account left every uploaded file behind. delete_account promises in
its own docstring to erase "the account and all associated data for good", but
removed only database rows — so every scan of a lab report, prescription photo
and picture of a rash stayed in uploads/ forever, with the row that identified
them gone. That is a privacy failure before it is a storage one.

Nothing noticed a filling disk. Arogo self-hosts on a Pi; when the card fills,
SQLite writes start failing, which in this app means a logged dose quietly not
saving.
"""
import os

import pytest

import auth as auth_module
from app import create_app
from db.core import init_db, user_context, execute, new_id, now_iso
from db import storage as st

PW = "stor-pw-12345"


