# Fast lookup by ID
FOOD_BY_ID = {f['id']: f for f in FOOD_DB}

# Category list
CATEGORIES = sorted(set(f['category'] for f in FOOD_DB))

def search_food(query: str = '', category: str = '', limit: int = 80) -> list:
    q   = query.lower().strip()
    cat = category.lower().strip()
    results = FOOD_DB
    if cat:
        results = [f for f in results if f['category'].lower() == cat]
    if q:
        results = [f for f in results if q in f['name'].lower() or q in f.get('category','').lower()]
    # Ensure every result has 'calories' key (normalise legacy 'cal' key)
    out = []
    for f in results[:limit]:
        if 'calories' not in f and 'cal' in f:
            f = {**f, 'calories': f['cal']}
        out.append(f)
    return out

def get_food(food_id: str) -> dict | None:
    return FOOD_BY_ID.get(food_id)